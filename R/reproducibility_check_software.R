# ─────────────────────────────────────────────────────────────────────────────
# reproducibility_check: the files that belong to software, not to the analysis
#
# The module reproduces a paper's results: the scripts that turn the deposit's
# data into the paper's numbers and figures. Deposits also hold software: the
# paper's own R or Python package, a tool the authors copied into the deposit,
# a web application, the programs of a data logger. Running the files of such
# software says nothing about the paper's results: a file of a package's code
# "runs" without doing anything, and a tool's helper fails because it waits for
# arguments, a server or a device. These files get the outcome `not_analysis`
# and are not counted as scripts (#568).
#
# The principle: every analysis reported in the paper should be reproduced, so
# the question for each script is whether it holds results that go into the
# paper. Outside software, the usual analysis deposit, every script is taken to
# do so and runs. Inside software, a script counts only when something links
# it to the paper (stage 2); a package's vignettes and examples are mostly
# tutorials of the software on its own example data.
#
# No single signal separates the two. A package can hold the paper's analysis
# (a paper/ folder next to R/), an analysis deposit can hold a whole tool (a
# copy of cutadapt-1.1 or of Trinity), and a tool writes R scripts of its own
# into the analysis folders. So every script goes through this decision path.
#
# Stage 1: is the file part of software?
# 1. What the file is, wherever it sits (.repro_software_file()):
#    a. written by a program, not by the authors: its first lines say so
#       (Rcpp's RcppExports.R, rstantools, protocol buffers, Django
#       migrations: "Generated by ... do not edit"), or its name starts with
#       `__tmp` (the R scripts Trinity writes and runs, __tmp_runTMM.R). Such
#       a script outside software that reads a file is analysis after all:
#       Trinity's __tmp_runTMM.R normalises the paper's data;
#    b. the settings of the Sphinx documentation builder (a conf.py that names
#       Sphinx settings), or a file in a docs/ folder below such a conf.py,
#       except a notebook or a file in its tutorials/ or examples/, which do
#       what a vignette does; or a template of roxygen2 (man-roxygen/);
#    c. a part of a Django web application (it imports django or
#       rest_framework);
#    d. a script that builds, checks or packs software and reads no data
#       (devtools::check() or build(), pkgdown, roxygen2, the libraries rwinlib
#       holds for building a package on Windows, PyInstaller, nox);
#    e. a file under .github/, .gitlab/ or .circleci/ (automatic checks);
#    f. __init__.py, which makes its folder a Python package to import.
# 2. Which software the file sits in (.repro_software_roots()). A folder is the
#    root of software when the deposit lists in that folder
#    a. an R package: DESCRIPTION, with NAMESPACE or an R/ folder; or R/ next
#       to help files in man/ (*.Rd), which only a package has (the listing of
#       an archive can leave DESCRIPTION out);
#    b. a Python package: setup.py or setup.cfg, or pyproject.toml next to a
#       folder with __init__.py (an analysis can use pyproject.toml just to
#       list the packages it needs);
#       neither a. nor b. when a workflow beside it runs the package (a
#       Snakefile, _targets.R, make.R, Nextflow, dvc.yaml): that is the analysis
#       written as a package of commands (digitizing-the-coral-reef);
#    c. a web application: manage.py (Django);
#    d. compiled software: CMakeLists.txt, configure, configure.ac,
#       meson.build, Cargo.toml, go.mod, pom.xml or build.gradle;
#    e. a copy of a released tool: a folder, or the archive it came in, whose
#       name ends in a version (trinityrnaseq_r2012-06-08.tgz) that holds the
#       files of a program (build files, a bin/ folder, or code in another
#       language than R and Python), in a repository that also holds R or
#       Python code outside it; without that code, the folder is a release of
#       the authors' own code (analysis-v1.0). A GitHub release kept on Zenodo
#       (owner/repo-v1.0.zip/owner-repo-1a2b3c4) is the authors' own code
#       too. A released package (cutadapt-1.1, mapboxer_0.4.0.tar.gz) stays a
#       package (a. or b.): it may be the package the paper presents.
#    A file outside every root is analysis, unless step 1 applies. A root
#    belongs to its repository: a package in one repository says nothing about
#    the files of another.
# 3. In a web application or a copy of a released tool, or in a root nested in
#    one, every file is software: the examples of cvat-sdk inside CVAT are
#    examples of CVAT, and Trinity's Analysis/ folder is Trinity's.
# 4. Otherwise the paper's analysis can have a folder of its own inside the
#    software: paper/, manuscript/, analysis/, reproduc*/, replication/,
#    figures/, results/. A file in such a folder is analysis (unless the
#    folder is inside tests/: tests/analysis/ holds tests): the folder's name
#    links it to the paper's results.
# 5. Roots can be nested (ESP-IDF holds a compiled project per example and per
#    component). A file is software when, seen from any root it is in, the
#    outermost first, it is:
#    a. in a tests/ folder;
#    b. in compiled software, in a folder these projects use for their own code
#       and tools (tools/, components/, src/, lib/, test/, examples/, docs/,
#       ...), or in a compiled project nested in it (a module of a 3D Slicer
#       extension);
#    c. in an R package, in R/, src/, tools/ or exec/: the package's code;
#    d. in a Python package, in a folder with __init__.py, src/ or bin/ (the
#       package's code), or in docs/ or ci/.
#
# Stage 2 (.repro_sw_links()): the other files of software (vignettes,
# examples, demos, scripts, notebooks, data-raw, inst/, loose scripts, and in
# compiled software the files outside its code folders) count as the paper's
# analysis only when at least one of these links them to the paper; otherwise
# they are not_analysis ("it documents or tests the software").
# 6. a. the paper names the script (its file name; its name without extension,
#       or its folder, when that name is specific: a digit, an underscore or
#       two capitalised words, and not the software's own name), or its
#       rendered page (data-sources.html, a website's articles/data-sources);
#       not where the paper only points to it as documentation ("the main
#       tutorial", "see the vignette for more details") without naming a
#       figure, table, appendix or the results; or
#       an appendix or supplement that the script names ("Appendix S2");
#    b. the script names the paper's figures or tables: a comment that says
#       which figure or table it makes ("# Figure 3", "## Table S2"), text that
#       says so ("Figure 3 of the paper"), or a file it writes named after one
#       (fig3.png, table_1.csv). A vignette's captions (fig.cap, a caption
#       function) do not count;
#    c. a README of the deposit names the script next to a figure, table,
#       appendix or supplement, or "the results of the paper";
#    d. the code names a data file deposited with the paper: a data file
#       outside every software folder (the data of a package's own examples
#       sit inside it), or one inside that the paper itself names.
#    Whether the numbers a script prints match the paper is not used here: the
#    module reports that after a run.
# 7. A script left unlinked is linked after all, in the same repository, when a
#    script that runs reads a file it writes, source()s it or imports it; when it
#    reads a file a script that runs writes; or when it source()s or imports a
#    script linked to the paper; and so on along the chain (.repro_sw_chain()).
#    The pipeline that feeds a figure is part of the analysis even when nothing
#    names it. A name built from a pattern ("{metric}_per_hour.csv") matches
#    the names it can stand for.
#
# What the paths cannot tell is whether a package or tool is the paper's own.
# A tool's repository without any of the files of step 2 (PyRate, a set of
# Python programs) is treated as analysis.
# ─────────────────────────────────────────────────────────────────────────────

# Folder names that hold the paper's own analysis, also inside software (step 4).
.repro_sw_analysis_dir <- paste0(
  "^(paper|papers|manuscript|manuscripts|publication|article|analysis|analyses|",
  "reproduc[a-z_]*|replication[a-z_]*|figures?|results?|case[_ -]?stud(y|ies))$")
# Folder names of a package that are not its code (step 5).
.repro_sw_keep_dir <- paste0(
  "^(vignettes?|examples?|example[_-]?gallery|demos?|tutorials?|scripts?|notebooks?|",
  "data[-_]raw|inst|simulations?)$")
# Folders of compiled software that hold its own code and tools (step 5b).
.repro_sw_code_dir <- paste0(
  "^(tools?|utils?|util|components?|src|lib|libs|tests?|testing|unit[-_]tests?|",
  "examples?|ci|cmake|build|docs?|documentation|packaging|contrib|third[-_]?party|",
  "external|vendor|deps|ext|bin|plugins?|firmware)$")
.repro_sw_test_dir <- "^(tests?|testing|testthat)$"
.repro_sw_archive_ext <- "\\.(zip|tgz|tar|tar\\.gz|tar\\.bz2|7z|rar)$"

# The decision path above for each script. `paths` are the scripts' paths in
# their repository, `code_text_list` their code (a character vector of lines
# each), `structure_df` the files the deposit lists (file_path or file_name,
# and repo_name), `repos` each script's repository (NULL or NA when unknown).
# Returns a data frame, one row per script: `kind` (NA for analysis, else
# generated, docs, web_app, build, ci, package_init, package, test or tool),
# `software` (the name of the software, NA when none is known) and `why` (the
# sentence the report gives).
.repro_software_kind <- function(paths, code_text_list, structure_df = NULL, repos = NULL,
                                 paper_text = NULL, raw_text_list = NULL) {
  n <- length(paths)
  out <- data.frame(kind = rep(NA_character_, n), software = rep(NA_character_, n),
                    why = rep(NA_character_, n), links = rep(NA_character_, n))
  if (!n) return(out)
  paths <- sub("^(\\./|/)+", "", gsub("\\\\", "/", as.character(paths)))
  repos <- if (is.null(repos)) rep(NA_character_, n) else rep_len(as.character(repos), n)
  listed <- .repro_sw_listed(structure_df, paths, repos)
  roots <- .repro_software_roots(listed)
  ctx <- .repro_sw_context(listed, roots, paper_text)
  for (i in seq_len(n)) {
    code <- unlist(strsplit(as.character(code_text_list[[i]] %||% character(0)), "\n", fixed = TRUE))
    code <- iconv(code, "", "UTF-8", sub = "")
    code <- code[!is.na(code)]
    file <- .repro_software_file(paths[i], code, listed)
    place <- .repro_software_place(paths[i], repos[i], roots, listed)
    in_software <- !is.na(place$root_name)
    # what links it to the paper matters only for a file of software that steps
    # 1 to 5 did not already place (an example, a vignette, a loose script)
    needs_link <- in_software && is.na(place$kind) && !place$paper_dir && is.na(file$kind)
    links <- if (needs_link)
      .repro_sw_links(paths[i], code, .repro_sw_all_text(raw_text_list[[i]], paths[i], code), ctx,
                      place, repos[i]) else character(0)
    out$links[i] <- if (length(links)) paste(links, collapse = ", ") else NA_character_
    hit <- if (place$kind %in% c("web_app", "tool")) {
      # a part of a web application or of a copied tool, whatever it does
      place
    } else if (!is.na(file$kind)) {
      # what the file is; a script a program wrote that works on the paper's
      # data (Trinity's __tmp_runTMM.R in an analysis folder) is analysis
      if (file$kind == "generated" && !in_software && length(.repro_sw_reads_any(code)))
        list(kind = NA_character_, software = NA_character_)
      else list(kind = file$kind, software = place$root_name)
    } else if (!is.na(place$kind)) {
      place
    } else if (in_software && !place$paper_dir && !length(links)) {
      # 6. an example, vignette, notebook or loose script of software that
      # nothing links to the paper's results
      list(kind = "unlinked", software = place$root_name)
    } else list(kind = NA_character_, software = NA_character_)
    out$kind[i] <- hit$kind
    out$software[i] <- hit$software
  }
  out$why <- .repro_software_why(out$kind, out$software)
  out
}

# The paper's text, "" when there is none (a local folder checked on its own).
.repro_paper_text <- function(paper) {
  txt <- tryCatch(paper$text$text, error = function(e) NULL)
  if (is.null(txt) || !is.character(txt)) "" else paste(txt, collapse = "\n")
}

# What stage 2 needs once per deposit: the paper's text in lower case with
# single spaces, the lines of the deposit's README files, and the names of the
# data files deposited with the paper (not those software ships for its own
# examples and tests).
.repro_sw_context <- function(listed, roots, paper_text = NULL) {
  paper <- tolower(gsub("\\s+", " ", paste(paper_text %||% "", collapse = " ")))
  readme <- list()
  is_readme <- grepl("^readme", basename(listed$path), ignore.case = TRUE) &
    !is.na(listed$location) & nzchar(listed$location)
  for (k in which(is_readme)) {
    loc <- listed$location[k]
    if (!file.exists(loc) || isTRUE(file.size(loc) > 2e6)) next
    lines <- tryCatch(readLines(loc, warn = FALSE, encoding = "UTF-8"), error = function(e) character(0))
    readme[[length(readme) + 1]] <- tolower(iconv(lines, "", "UTF-8", sub = ""))
  }
  is_data <- grepl(.repro_sw_data_ext, listed$path, ignore.case = TRUE)
  list(paper = paper, readme = readme, data = .repro_sw_paper_data(listed, roots, paper),
       data_files = listed[is_data, c("repo", "path"), drop = FALSE])
}

.repro_sw_data_ext <- paste0(
  "\\.(csv|tsv|txt|dat|xlsx?|ods|rds|rdata|rda|sav|dta|json|geojson|nc|h5|hdf5|tiff?|shp|gpkg|",
  "fasta|fa|fastq|nex|nexus|tre|tree|phy|wav|mat|npy|npz|pkl|pickle|parquet|feather|asc|grd)$")

# The names (lower case) of the data files deposited with the paper: every data
# file of the deposit outside software (a package's data/, extdata/ or tests/
# hold the data of its own examples), and a data file inside software that the
# paper names (its data availability statement).
.repro_sw_paper_data <- function(listed, roots, paper = "") {
  is_data <- grepl(.repro_sw_data_ext, listed$path, ignore.case = TRUE) &
    !grepl("^(readme|license|licence|requirements|description|namespace|citation)", basename(listed$path),
           ignore.case = TRUE)
  in_software <- vapply(seq_len(nrow(listed)), function(k) is_data[k] &&
    any(roots$repo == listed$repo[k] & (!nzchar(roots$root) | startsWith(listed$path[k], paste0(roots$root, "/")))),
    logical(1))
  nm <- tolower(basename(listed$path))
  outside <- unique(nm[is_data & !in_software])
  named <- unique(nm[is_data & in_software & nchar(nm) >= 8])
  named <- named[vapply(named, function(f) nzchar(paper) && grepl(f, paper, fixed = TRUE), logical(1))]
  out <- unique(c(outside, named))
  out <- out[nchar(out) >= 5]
  attr(out, "named") <- named
  out
}

# The files a script reads (names), from repro_file_io().
.repro_sw_reads_any <- function(code) {
  io <- tryCatch(repro_file_io(list(x = code), "R"), error = function(e) NULL)
  if (is.null(io) || !nrow(io)) return(character(0))
  unlist(io$reads, use.names = FALSE)
}

# All the text of a script: its code with its comments and, for a notebook or an
# R Markdown file, the text between the code (code_text_list holds code only).
.repro_sw_all_text <- function(raw, path, code) {
  raw <- unlist(strsplit(as.character(raw %||% character(0)), "\n", fixed = TRUE))
  if (!length(raw)) return(code)
  if (grepl("\\.ipynb$", path, ignore.case = TRUE)) {
    nb <- tryCatch(jsonlite::fromJSON(paste(raw, collapse = "\n"), simplifyVector = FALSE),
                   error = function(e) NULL)
    if (is.null(nb$cells)) return(code)
    raw <- unlist(lapply(nb$cells, function(cl)
      unlist(strsplit(paste(unlist(cl$source), collapse = ""), "\n", fixed = TRUE))))
  }
  raw <- iconv(raw, "", "UTF-8", sub = "")
  raw[!is.na(raw)]
}

# Stage 2: what links a script inside software to the paper's results; the
# names of the signals found, none when nothing does. `code` is the code that
# runs, `text` all the script's text.
.repro_sw_links <- function(path, code, text, ctx, place, repo) {
  root_name <- place$root_name
  links <- character(0)
  base <- basename(path)
  # bytes that are not UTF-8 stop tolower() and the searches below
  code <- .utf8_lines(code)
  text <- .utf8_lines(text)
  # 2. the paper names the code, or an appendix the code names
  if (nzchar(ctx$paper)) {
    if (.repro_sw_named_in(ctx$paper, path, root_name, repo)) links <- c(links, "paper_names_it")
    app <- .repro_sw_appendix(tolower(text))
    if (length(app) && any(vapply(app, function(a) grepl(a, ctx$paper, fixed = TRUE), logical(1))))
      links <- c(links, "appendix")
  }
  # 3. the code names the paper's figures or tables
  if (length(.repro_sw_names_results(text))) links <- c(links, "names_results")
  # 4. a README maps it to the paper
  if (.repro_sw_readme_maps(ctx$readme, base)) links <- c(links, "readme")
  # 5. it reads the paper's data; a file of that name that the software itself
  # ships (rcoalescence's vignettes/images/ beside a copy elsewhere) is its own
  df <- ctx$data_files
  own <- df$repo == (place$root_repo %|na|% "") &
    (!nzchar(place$root %|na|% "") | startsWith(df$path, paste0(place$root, "/")))
  data <- union(setdiff(ctx$data, tolower(basename(df$path[own]))), attr(ctx$data, "named"))
  if (.repro_sw_reads_paper_data(tolower(code), data)) links <- c(links, "data")
  links
}

`%|na|%` <- function(x, y) if (is.null(x) || is.na(x)) y else x

.repro_sw_escape <- function(x) gsub("([][{}()+*^$|\\\\?.])", "\\\\\\1", x)

# A name specific enough that the paper naming it means this file: with a digit
# or an underscore, or two capitalised words, and at least 6 letters (a hyphen
# is not enough: "step-by-step" is also a phrase).
.repro_sw_specific <- function(x) {
  nchar(x) >= 6 & (grepl("[0-9_]", x) | grepl("[a-z][A-Z]", x)) &
    !tolower(x) %in% c("r_code", "r-code", "code_r", "scripts_r", "r_scripts", "python_code")
}

# Signal 2: the paper names the script (with its extension, or a specific name
# without it), or the folder it sits in, when that name is specific and not the
# software's own name.
.repro_sw_named_in <- function(paper, path, root_name, repo) {
  base <- basename(path)
  stem <- sub("\\.[^.]+$", "", base)
  folder <- basename(dirname(path))
  own <- tolower(c(root_name, repo))
  # A mention counts unless what is around it only points to documentation
  # ("the main tutorial", "see the vignette for more details") and says
  # nothing of results (a figure, a table, an analysis, an appendix).
  counts <- function(pattern) {
    at <- gregexpr(pattern, paper, perl = TRUE)[[1]]
    at <- at[at > 0]
    any(vapply(at, function(k) {
      # the sentence it is in (a figure caption next to it is not about it)
      before <- substr(paper, max(1, k - 200), k)
      after <- substr(paper, k + 1, k + 200)
      start <- regexpr("\\.\\s[^.]*$", before)
      around <- paste0(if (start > 0) substring(before, start + 2) else before,
                       sub("\\.\\s.*$", "", after))
      !grepl("tutorial|for (more )?details|detailed description|step-by-step|documentation|vignettes? of the package|main vignette|retrieved from",
             around, perl = TRUE) ||
        grepl("\\b(fig(ure)?s?\\.?|tables?) ?s?[0-9]|\\bappendix|\\bsupplement|reproduc|\\bour (analys[ie]s|results)",
              around, perl = TRUE)
    }, logical(1)))
  }
  word <- function(x) counts(paste0("(^|[^a-z0-9_.-])", .repro_sw_escape(tolower(x)), "($|[^a-z0-9_-])"))
  if (nchar(base) >= 5 && word(base)) return(TRUE)
  # a name of its own, not the software's (a package's main vignette, GIFT.Rmd)
  if (.repro_sw_specific(stem) && !tolower(stem) %in% own && word(stem)) return(TRUE)
  # the rendered vignette or notebook: data-sources.html, a package website's
  # articles/data-sources
  low <- tolower(stem)
  if (nchar(stem) >= 4 && (word(paste0(stem, ".html")) || word(paste0(stem, ".pdf")) ||
                           counts(paste0("(articles|vignettes)/", .repro_sw_escape(low), "($|[^a-z0-9_-])"))))
    return(TRUE)
  folder != "." && .repro_sw_specific(folder) && !tolower(folder) %in% own && word(folder)
}

# The appendices and supplements a script names ("appendix s2").
.repro_sw_appendix <- function(lc) {
  x <- unlist(regmatches(lc, gregexpr("\\b(appendix|supplementary (material|information|file|text)|supporting information|online resource) ?s?[0-9]+\\b", lc)))
  unique(gsub("\\s+", " ", x))
}

# Signal 3: the lines in which the code names the paper's figures or tables: a
# comment that says which figure or table of the paper it makes, or a file it
# writes named after one (fig3.png, table_1.csv). A vignette's own captions
# ("Figure 1. The example data") and figure counters do not count.
.repro_sw_names_results <- function(code) {
  # a file name that starts with the figure or table (fig3.png, results/Table_S1.csv,
  # map_fig2.pdf), not one that only holds the word (Raven's x.Table.1.selections.txt)
  out_file <- grepl(paste0("[\"'/_-](fig|figure|tab|table)[ _-]?s?[0-9]+[a-z]?([_-][^\"'/]*)?",
                           "\\.(png|pdf|jpe?g|tiff?|svg|eps|csv|xlsx?|docx?|html|txt|rds)[\"']"),
                    code, ignore.case = TRUE, perl = TRUE) &
    # showing a picture is not making one (knitr::include_graphics("images/runauto_fig1.png"))
    !grepl("include_graphics|readpng|imread|image_read|!\\[", code, ignore.case = TRUE)
  # text that says it is about the paper's figure ("Figure 3 of the paper")
  paper_fig <- grepl(paste0("\\b(fig(ure)?s?\\.?|table)\\s*s?[0-9]+[a-z]?\\s+(of|in|from) (the|our|this) ",
                            "(main )?(paper|manuscript|article|main text|publication)"),
                     code, ignore.case = TRUE, perl = TRUE)
  comment <- grepl("^\\s*(#|//)", code) &
    grepl("\\b(fig(ure)?s?\\.?|table|appendix|supplementary (fig(ure)?|table))\\s*s?[0-9]+[a-z]?\\b",
          code, ignore.case = TRUE, perl = TRUE) &
    !grepl("fig\\.cap|caption|captioner", code, ignore.case = TRUE)
  code[out_file | comment | paper_fig]
}

# Signal 4: a README line names the script together with a figure, table or
# section of the paper.
.repro_sw_readme_maps <- function(readme, base) {
  if (!length(readme)) return(FALSE)
  b <- tolower(base)
  stem <- sub("\\.[^.]+$", "", b)
  any(vapply(readme, function(lines) {
    hit <- which(grepl(b, lines, fixed = TRUE) | (.repro_sw_specific(stem) & grepl(stem, lines, fixed = TRUE)))
    if (!length(hit)) return(FALSE)
    near <- lines[unique(pmin(length(lines), pmax(1, c(hit - 1, hit, hit + 1))))]
    any(grepl("\\b(fig(ure)?s?\\.?|table|appendix|supplement[a-z]*)\\s*s?[0-9]+|\\b(results?|analys[ie]s) (in|of|for) the (paper|manuscript|article)",
              near, perl = TRUE))
  }, logical(1)))
}

# Signal 5: the code names a data file deposited with the paper, other than
# through system.file() or a package's example data.
.repro_sw_reads_paper_data <- function(lc, data) {
  if (!length(data) || !length(lc)) return(FALSE)
  lc <- lc[!grepl("system\\.file|extdata|pkg_resources|importlib\\.resources", lc)]
  txt <- paste(lc, collapse = "\n")
  any(vapply(data, function(f) grepl(f, txt, fixed = TRUE), logical(1)))
}

# The deposit's files, with their repository: the listed files, and the
# scripts themselves (a listing can leave them out). `repo` is "" when the
# repository is not known.
.repro_sw_listed <- function(structure_df, paths, repos) {
  p <- character(0); r <- character(0); loc <- character(0)
  if (!is.null(structure_df) && nrow(structure_df)) {
    p <- if ("file_path" %in% names(structure_df)) as.character(structure_df$file_path) else
      as.character(structure_df$file_name)
    none <- is.na(p) | !nzchar(p)
    if ("file_name" %in% names(structure_df)) p[none] <- as.character(structure_df$file_name[none])
    r <- if ("repo_name" %in% names(structure_df)) as.character(structure_df$repo_name) else
      rep(NA_character_, length(p))
    loc <- if ("file_location" %in% names(structure_df)) as.character(structure_df$file_location) else
      rep(NA_character_, length(p))
  }
  p <- sub("^(\\./|/)+", "", gsub("\\\\", "/", c(p, paths)))
  r <- c(r, repos)
  r[is.na(r)] <- ""
  loc <- c(loc, rep(NA_character_, length(paths)))
  keep <- !is.na(p) & nzchar(p) & !duplicated(paste(r, p))
  data.frame(repo = r[keep], path = p[keep], location = loc[keep])
}

# Step 1: what the file itself is. Returns list(kind).
.repro_software_file <- function(path, code, listed) {
  base <- tolower(basename(path))
  is_py <- grepl("\\.py$", base)
  code <- iconv(code, "", "UTF-8", sub = "")
  code <- code[!is.na(code)]
  has <- function(pat, x = code) any(grepl(pat, x, perl = TRUE))
  kind <- if (startsWith(base, "__tmp") ||
              has(paste0("(?i)(generated by (using )?(rcpp|rstantools|the protocol buffer compiler|",
                         "django|'django-admin|swig|cython)|this file was generated by rcpp|",
                         "generated.{0,60}do not edit)"), utils::head(code, 12))) "generated"
  else if ((base == "conf.py" && has("(?i)(sphinx|html_theme|^\\s*extensions\\s*=|master_doc|source_suffix)")) ||
           .repro_sw_below_sphinx(path, listed) || grepl("(^|/)man-roxygen/", path)) "docs"
  else if (is_py && has("^\\s*(from|import)\\s+(django|rest_framework)\\b")) "web_app"
  else if (.repro_sw_builds(code, is_py)) "build"
  else if (grepl("(^|/)\\.(github|gitlab|circleci)/", path)) "ci"
  else if (base == "__init__.py") "package_init"
  else NA_character_
  list(kind = kind)
}

# A file in a docs/ folder that holds a Sphinx conf.py (its themes, extensions),
# but not its tutorials or examples, which do what a vignette does.
.repro_sw_below_sphinx <- function(path, listed) {
  # a notebook in the documentation is a worked example too
  if (grepl("\\.(ipynb|rmd|qmd)$", path, ignore.case = TRUE)) return(FALSE)
  confs <- dirname(listed$path[basename(listed$path) == "conf.py"])
  confs <- confs[grepl("(^|/)(docs?|documentation)(/source)?$", confs, ignore.case = TRUE)]
  below <- confs[startsWith(path, paste0(confs, "/"))]
  if (!length(below)) return(FALSE)
  folders <- tolower(utils::head(strsplit(substring(path, nchar(below[1]) + 2), "/", fixed = TRUE)[[1]], -1))
  !any(grepl(.repro_sw_keep_dir, folders))
}

# A script that builds, checks or packs software, and reads no data (step 1d).
.repro_sw_builds <- function(code, is_py) {
  code <- code[!grepl("^\\s*#", code)]
  has <- function(pat) any(grepl(pat, code, perl = TRUE))
  if (is_py)
    return(has("^\\s*(import|from)\\s+(PyInstaller|nox|versioneer|cx_Freeze|py2exe|py2app)\\b") ||
             has("['\"]pyinstaller['\"]"))
  # installing a package, or saving a package's data (usethis::use_data()), is
  # what an analysis does too; rwinlib holds the libraries a package needs to
  # be built on Windows (tools/winlibs.R)
  builds <- has(paste0("\\b(devtools::(check|build|document|build_manual|build_vignettes|release|",
                       "submit_cran)|pkgdown::build_[a-z]+|roxygen2::roxygeni[sz]e|",
                       "usethis::use_(?!data)[a-z_]+|Rcpp::compileAttributes)\\s*\\(")) ||
    has("github\\.com/rwinlib/")
  builds && !.repro_sw_reads_data(code)
}

# Whether R code reads a data file.
.repro_sw_reads_data <- function(code) {
  any(grepl(paste0("\\b(read[._](csv2?|table|delim|tsv|xlsx?|excel|dta|sav|spss|stata|fwf|rds|sas)|",
                   "readRDS|readxl::|fread|load|st_read|readOGR|raster|rast|nc_open|vroom|",
                   "read_sf|readLines|scan)\\s*\\("), code, perl = TRUE))
}

# Step 2: the roots of software among the deposit's files, one row per root:
# repo, root (the folder, "" for the top of the repository), type (tool,
# web_app, r_package, py_package, compiled) and name.
.repro_software_roots <- function(listed) {
  empty <- data.frame(repo = character(0), root = character(0), type = character(0),
                      name = character(0))
  if (is.null(listed) || !nrow(listed)) return(empty)
  base <- basename(listed$path)
  dir <- dirname(listed$path)
  dir[dir == "."] <- ""
  key <- paste(listed$repo, dir, sep = "\r")
  key_repo <- function(k) sub("\r.*", "", k)
  key_dir <- function(k) sub("^[^\r]*\r", "", k)
  parent <- function(k) paste(key_repo(k), sub("(^|/)[^/]*$", "", key_dir(k)), sep = "\r")
  in_dir <- function(names) unique(key[base %in% names])
  # a. R package; help files (man/*.Rd) next to R/ only occur in a package, and
  # a listing of an archive can leave DESCRIPTION out
  r_dirs <- parent(unique(key[grepl("\\.[Rr]$", base) & basename(dir) == "R"]))
  rd_dirs <- parent(unique(key[grepl("\\.Rd$", base) & basename(dir) == "man"]))
  r_pkg <- union(intersect(in_dir("DESCRIPTION"), union(in_dir("NAMESPACE"), r_dirs)),
                 intersect(r_dirs, rd_dirs))
  # b. Python package; pyproject.toml only next to a folder with __init__.py,
  # directly or in src/
  init_dirs <- unique(key[base == "__init__.py" & nzchar(dir)])
  in_src <- init_dirs[basename(dirname(key_dir(init_dirs))) == "src"]
  py_pkg <- union(in_dir(c("setup.py", "setup.cfg")),
                  intersect(in_dir("pyproject.toml"), c(parent(init_dirs), parent(parent(in_src)))))
  # a package that a workflow beside it runs (a Snakefile, targets) is the
  # analysis written as a package of commands, not software of its own
  workflow <- in_dir(c("Snakefile", "snakefile", "dvc.yaml", "main.nf", "nextflow.config", "_targets.R",
                       "make.R"))
  # (and so is a package nested in it)
  run_by_workflow <- function(k) vapply(k, function(x) any(key_repo(workflow) == key_repo(x) &
    (!nzchar(key_dir(workflow)) | key_dir(x) == key_dir(workflow) |
       startsWith(key_dir(x), paste0(key_dir(workflow), "/")))), logical(1))
  if (length(workflow)) {
    r_pkg <- r_pkg[!run_by_workflow(r_pkg)]
    py_pkg <- py_pkg[!run_by_workflow(py_pkg)]
  }
  # c. web application
  web <- in_dir("manage.py")
  # d. compiled software
  compiled <- in_dir(c("CMakeLists.txt", "configure", "configure.ac", "meson.build", "Cargo.toml",
                       "go.mod", "pom.xml", "build.gradle", "build.gradle.kts"))
  # e. a copy of a released tool
  all_dirs <- unique(unlist(lapply(unique(key[nzchar(dir)]), function(k) {
    parts <- strsplit(key_dir(k), "/", fixed = TRUE)[[1]]
    paste(key_repo(k), vapply(seq_along(parts), function(j) paste(parts[seq_len(j)], collapse = "/"), ""),
          sep = "\r")
  })))
  # the folder, or the archive it came in (mapboxer_0.4.0.tar.gz, the form in
  # which CRAN hands out an R package), ends in a version
  version_end <- "[A-Za-z][-_](v?[0-9]+(\\.[0-9]+)+[a-z]?|r?[0-9]{4}-[0-9]{2}-[0-9]{2})$"
  dname <- basename(key_dir(all_dirs))
  is_archive <- grepl(.repro_sw_archive_ext, dname, ignore.case = TRUE)
  versioned <- all_dirs[grepl(version_end, dname) |
                          (is_archive & grepl(version_end, sub(.repro_sw_archive_ext, "", dname, ignore.case = TRUE)))]
  pkg_roots <- c(r_pkg, py_pkg)
  tool <- versioned[vapply(versioned, function(k) {
    d <- key_dir(k)
    # a released package (cutadapt-1.1, mapboxer_0.4.0.tar.gz/mapboxer) stays a
    # package: it may be the one the paper presents, with its examples
    pkg_dirs <- key_dir(pkg_roots[key_repo(pkg_roots) == key_repo(k)])
    if (any(pkg_dirs == d | dirname(pkg_dirs) == d)) return(FALSE)
    same_repo <- listed$repo == key_repo(k)
    inside <- same_repo & startsWith(listed$path, paste0(d, "/"))
    # a release of a GitHub repository (owner/repo-v1.0.zip/owner-repo-1a2b3c4)
    # is how Zenodo keeps the authors' own code
    if (any(grepl("^[^/]+-[0-9a-f]{7}/", substring(listed$path[inside], nchar(d) + 2)))) return(FALSE)
    b <- basename(listed$path[inside])
    program <- any(b %in% c("setup.py", "configure", "CMakeLists.txt", "INSTALL", "build.xml")) ||
      any(startsWith(listed$path[inside], paste0(d, "/bin/"))) ||
      any(grepl("\\.(pl|pm|c|cc|cpp|h|hpp|java|jar|f|f90|go|rs)$", b, ignore.case = TRUE))
    if (!program) return(FALSE)
    # the authors' own code, released as analysis-v1.0, holds all the code there is
    archive <- sub(paste0("^(.*", sub("\\$$", "", .repro_sw_archive_ext), ")/.*$"), "\\1", d, ignore.case = TRUE)
    outside <- same_repo & !startsWith(listed$path, paste0(archive, "/")) & !startsWith(listed$path, paste0(d, "/"))
    any(grepl("\\.(r|rmd|qmd|py|ipynb)$", listed$path[outside], ignore.case = TRUE))
  }, logical(1))]
  # one type per folder, the first of: a tool (cutadapt-1.1 is also a Python
  # package), a web application, a package, compiled software
  roots <- rbind(
    data.frame(key = tool, type = rep("tool", length(tool))),
    data.frame(key = web, type = rep("web_app", length(web))),
    data.frame(key = r_pkg, type = rep("r_package", length(r_pkg))),
    data.frame(key = py_pkg, type = rep("py_package", length(py_pkg))),
    data.frame(key = compiled, type = rep("compiled", length(compiled))))
  if (!nrow(roots)) return(empty)
  roots <- roots[!duplicated(roots$key), , drop = FALSE]
  data.frame(repo = key_repo(roots$key), root = key_dir(roots$key), type = roots$type,
             name = .repro_sw_name(key_dir(roots$key), key_repo(roots$key)))
}

# The software's name: its folder, without the owner and commit that GitHub's
# archives add (owner/repo-v1.0.zip/owner-repo-1a2b3c4), or the repository's
# name for a root at the top of the repository.
.repro_sw_name <- function(root, repo) {
  nm <- sub(.repro_sw_archive_ext, "", basename(root), ignore.case = TRUE)
  owner <- basename(dirname(dirname(root)))
  gh <- grepl("-[0-9a-f]{7}$", nm) & nzchar(owner) & owner != "." & startsWith(nm, paste0(owner, "-"))
  nm[gh] <- sub("-[0-9a-f]{7}$", "", substring(nm[gh], nchar(owner[gh]) + 2))
  nm[!nzchar(root)] <- repo[!nzchar(root)]
  nm[is.na(nm) | !nzchar(nm)] <- NA_character_
  nm
}

# Steps 3 to 5: where the file sits. Returns list(kind, software, root_name),
# root_name being the name of the nearest root the file is in (NA when none).
.repro_software_place <- function(path, repo, roots, listed) {
  # root and root_repo: the nearest root the file is in
  root <- NA_character_; root_repo <- NA_character_
  out <- function(kind = NA_character_, software = NA_character_, root_name = NA_character_,
                  paper_dir = FALSE)
    list(kind = kind, software = software, root_name = root_name, paper_dir = paper_dir,
         root = root, root_repo = root_repo)
  if (!nrow(roots)) return(out())
  repo <- if (is.na(repo)) "" else repo
  # a root at the top of a repository applies to a file of that repository, or,
  # when the file's repository is not known, only in a deposit of one repository
  one_repo <- length(unique(listed$repo[nzchar(listed$repo)])) <= 1
  same <- roots$repo == repo | (!nzchar(repo) & (nzchar(roots$root) | one_repo))
  inside <- same & (!nzchar(roots$root) | startsWith(path, paste0(roots$root, "/")))
  if (!any(inside)) return(out())
  r <- roots[inside, , drop = FALSE]
  r <- r[order(-nchar(r$root)), , drop = FALSE]   # the nearest root first
  near_name <- r$name[1]
  root <- r$root[1]; root_repo <- r$repo[1]
  parts_below <- function(root) {
    below <- if (nzchar(root)) substring(path, nchar(root) + 2) else path
    utils::head(strsplit(below, "/", fixed = TRUE)[[1]], -1)
  }
  # 3. a web application or a copy of a tool, and any root inside one: the
  # outermost names the software
  wt <- r[r$type %in% c("web_app", "tool"), , drop = FALSE]
  if (nrow(wt)) return(out(wt$type[nrow(wt)], wt$name[nrow(wt)], near_name))
  # 4. the paper's analysis in a folder of its own (not one inside tests/:
  # tests/analysis/ holds tests)
  outer <- tolower(parts_below(r$root[nrow(r)]))
  at_analysis <- which(grepl(.repro_sw_analysis_dir, outer))
  at_test <- which(grepl(.repro_sw_test_dir, outer))
  if (length(at_analysis) && (!length(at_test) || at_analysis[1] < at_test[1]))
    return(out(root_name = near_name, paper_dir = TRUE))
  init_dirs <- unique(paste(listed$repo, dirname(listed$path), sep = "\r")[basename(listed$path) == "__init__.py"])
  # 5. seen from each root, the outermost first, which names the software (ESP-IDF
  # rather than one of its components)
  for (j in rev(seq_len(nrow(r)))) {
    parts <- parts_below(r$root[j])
    folders <- tolower(parts)
    name <- r$name[j]
    if (any(grepl(.repro_sw_test_dir, folders))) return(out("test", name, near_name))
    if (r$type[j] == "compiled") {
      # a compiled project inside another one is a part of it (a module of a 3D
      # Slicer extension, an example project of ESP-IDF)
      inner <- r$type[seq_len(j - 1)] == "compiled"
      if (any(grepl(.repro_sw_code_dir, folders)) || any(inner)) return(out("tool", name, near_name))
      next
    }
    if (!length(folders)) next
    keep_at <- which(grepl(.repro_sw_keep_dir, folders))
    if (r$type[j] == "r_package") {
      if (!length(keep_at) && folders[1] %in% c("r", "src", "tools", "exec"))
        return(out("package", name, near_name))
      next
    }
    # a Python package's code: below a folder with __init__.py (also its
    # scripts/ folder, cutadapt/scripts/), or in src/ or bin/; a notebook is
    # never a module to import, but a worked example
    if (grepl("\\.(ipynb|rmd|qmd)$", path, ignore.case = TRUE)) next
    dirs <- vapply(seq_along(parts), function(k)
      paste(c(if (nzchar(r$root[j])) r$root[j], parts[seq_len(k)]), collapse = "/"), "")
    pkg_at <- which(paste(r$repo[j], dirs, sep = "\r") %in% init_dirs)
    if (length(pkg_at) && (!length(keep_at) || pkg_at[1] < keep_at[1]))
      return(out("package", name, near_name))
    if (length(keep_at)) next
    if (folders[1] %in% c("src", "bin")) return(out("package", name, near_name))
    if (folders[1] %in% c("docs", "doc")) return(out("docs", name, near_name))
    if (folders[1] == "ci") return(out("ci", name, near_name))
  }
  out(root_name = near_name)
}

# The sentence for a file that is not part of the analysis: `why` from
# .repro_software_kind(), or, when NA, the one for a package's tests and the
# setup.py that installs a package (.repro_is_r_test(), .repro_is_py_test()).
.repro_not_analysis_why <- function(why) {
  ifelse(is.na(why), "It is a test of a package or the file that installs it, not part of the analysis.", why)
}

# Step 7, after stage 2: the scripts the paper's analysis depends on. Nothing
# may name the pipeline that feeds a figure: in FluxRGNN, run_baselines.py
# writes the summary.csv that run_experiments.py reads, and evaluate_performance.py
# writes the rmse_per_hour.csv a notebook reads as "{metric}_per_hour.csv". So a
# script left unlinked by stage 2 is linked after all, in the same repository,
# when
#   a. a script that runs (kind NA) reads a file it writes, source()s it or
#      imports it: the analysis needs it;
#   b. it reads a file that a script that runs writes: it works on the
#      analysis's results;
#   c. it source()s or imports a script linked to the paper (a link of stage 2,
#      or of this step): it drives that part of the analysis;
# repeated, so the whole chain is linked. A name built from a pattern
# ("{metric}_per_hour.csv", "fig_%d.png") matches any name it can stand for.
# `kind` is .repro_software_kind()'s column, `links` its column of links (NA
# when none), `file_names` the scripts' names (as in `io`), `io`
# repro_file_io()'s result, `imported` .repro_py_imported()'s (imported file ->
# the files that import it), `repos` each script's repository.
# Returns, per script, how it is linked ("run.py needs what it makes"; NA when
# not linked).
.repro_sw_chain <- function(kind, file_names, io = NULL, imported = NULL, repos = NULL, links = NULL) {
  n <- length(kind)
  through <- rep(NA_character_, n)
  if (!any(kind %in% "unlinked") || is.null(io) || !nrow(io)) return(through)
  repos <- if (is.null(repos)) rep("", n) else ifelse(is.na(repos), "", as.character(repos))
  at <- match(file_names, io$file_name)
  get <- function(col, i) if (is.na(at[i]) || is.null(io[[col]])) character(0) else tolower(io[[col]][[at[i]]])
  stem <- function(f) tolower(basename(gsub("\\\\", "/", f)))
  # whether a name in one list can be a name in the other, patterns included
  as_regex <- function(x) {
    x <- gsub("([.+^$()|\\[\\]\\\\])", "\\\\\\1", x, perl = TRUE)
    x <- gsub("\\{[^}]*\\}|%[0-9.]*[sdif]|\\*", ".+", x, perl = TRUE)
    paste0("^", x, "$")
  }
  meets <- function(a, b) {
    if (!length(a) || !length(b)) return(FALSE)
    if (length(intersect(a, b))) return(TRUE)
    pat_a <- a[grepl("\\{|%|\\*", a)]; pat_b <- b[grepl("\\{|%|\\*", b)]
    any(vapply(as_regex(pat_a), function(p) any(grepl(p, b, perl = TRUE)), logical(1))) ||
      any(vapply(as_regex(pat_b), function(p) any(grepl(p, a, perl = TRUE)), logical(1)))
  }
  # what u imports: the files whose importers include u
  imports_of <- function(u) names(imported)[vapply(imported, function(v) file_names[u] %in% v, logical(1))]
  runs <- is.na(kind)
  strong <- runs & !is.na(links %||% rep(NA_character_, n))
  repeat {
    added <- FALSE
    for (u in which(kind %in% "unlinked" & is.na(through))) {
      same <- repos == repos[u]
      writes <- get("writes", u); reads <- get("reads", u)
      needed_by <- which(runs & same)[vapply(which(runs & same), function(j)
        meets(writes, get("reads", j)) || stem(file_names[u]) %in% get("sources", j) ||
          file_names[j] %in% (imported[[file_names[u]]] %||% character(0)), logical(1))]
      works_on <- which(runs & same)[vapply(which(runs & same), function(j) meets(reads, get("writes", j)), logical(1))]
      drives <- which(strong & same)[stem(file_names[which(strong & same)]) %in%
                                       c(get("sources", u), tolower(imports_of(u)))]
      hit <- c(needed_by, works_on, drives)
      if (length(hit)) {
        through[u] <- if (length(needed_by)) sprintf("%s needs what it makes", file_names[needed_by[1]])
          else if (length(works_on)) sprintf("it works on what %s makes", file_names[works_on[1]])
          else sprintf("it runs %s", file_names[drives[1]])
        runs[u] <- TRUE
        strong[u] <- TRUE
        added <- TRUE
      }
    }
    if (!added) break
  }
  through
}

# What links a file of software to the paper, in words, for `table$paper_link`:
# the codes of stage 2 ("paper_names_it, data") become sentences, a link of step
# 7 is one already.
.repro_sw_link_text <- function(links) {
  words <- c(paper_names_it = "the paper names it",
             appendix = "it names an appendix or supplement the paper names",
             names_results = "it names the paper's figures or tables",
             readme = "a README names it next to a figure or table",
             data = "it reads data deposited with the paper")
  vapply(links, function(l) {
    if (is.na(l) || !nzchar(l)) return(NA_character_)
    parts <- strsplit(l, ", ", fixed = TRUE)[[1]]
    paste(ifelse(parts %in% names(words), words[parts], parts), collapse = "; ")
  }, character(1), USE.NAMES = FALSE)
}

# The sentence the report gives for each kind of file.
.repro_software_why <- function(kind, software) {
  sw <- ifelse(is.na(software), "", sprintf(" %s", software))
  txt <- c(
    generated = "A program wrote it while it ran; it is not one of the authors' scripts.",
    docs = "It belongs to the documentation of the software%s, not to the analysis.",
    web_app = "It is part of the web application%s, not of the analysis.",
    build = "It builds, checks or packs software, and is not part of the analysis.",
    ci = "It is part of the automatic checks of the software%s, not of the analysis.",
    package_init = "It makes its folder a Python package that other files import; it is not a script.",
    package = "It is part of the code of the package%s, which other files use; it is not a script to run on its own.",
    test = "It is a test of the software%s, not part of the analysis.",
    tool = "It is part of the software%s, which the deposit includes; it is not part of the analysis.",
    unlinked = "It documents or tests the software%s; nothing links it to the paper's results.")
  out <- rep(NA_character_, length(kind))
  known <- !is.na(kind) & kind %in% names(txt)
  out[known] <- vapply(which(known), function(i)
    if (grepl("%s", txt[[kind[i]]], fixed = TRUE)) sprintf(txt[[kind[i]]], sw[i]) else txt[[kind[i]]],
    character(1))
  out
}
