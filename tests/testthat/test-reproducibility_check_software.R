                                             "f <- function(x) x", "import numpy", "import pandas as pd"))
  expect_true(all(is.na(out$kind)))
  expect_true(all(is.na(out$why)))
  expect_equal(nrow(.repro_software_kind(character(0), list())), 0)
})

